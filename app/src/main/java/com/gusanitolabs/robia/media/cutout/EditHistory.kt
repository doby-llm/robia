package com.gusanitolabs.robia.media.cutout

import java.io.File
import java.util.TreeMap
import java.util.UUID

/** Bytes of edit history that the photos of one editing session may hold together (REQ-ED-03: 64 MB). */
internal const val EDIT_HISTORY_BUDGET_BYTES = 64L shl 20

/** A checkpoint every this many ops, so an undo replays at most this many ops. */
internal const val CHECKPOINT_INTERVAL = 8

/** One change of a photo's alpha. Replaying the ops from the automatic alpha reproduces every alpha bit-exactly. */
internal sealed interface EditOp {
    /** Bytes this op holds in the history budget. */
    val bytes: Long

    /** Smart selection: the dilated selection ([hardSelection]) as runs of 0 and 1. */
    class Hard(val mode: RefineSession.Mode, val selected: BitRuns) : EditOp {
        override val bytes: Long get() = selected.bytes
    }

    /** Brush stroke: [points] as x, y pairs in photo pixels; the mask is regenerated by [brushMask] on every replay. */
    class Brush(
        val mode: RefineSession.Mode,
        val points: FloatArray,
        val radiusPx: Float,
        val featherPx: Float,
    ) : EditOp {
        override val bytes: Long get() = points.size * 4L

        fun pairs(): List<Pair<Float, Float>> = List(points.size / 2) { points[2 * it] to points[2 * it + 1] }
    }

    /** Any other soft mask (0..1 per pixel), stored as runs. */
    class Soft(val mode: RefineSession.Mode, val mask: RunLengthAlpha) : EditOp {
        override val bytes: Long get() = mask.bytes
    }

    /** Back to the automatic alpha of the current base. */
    data object Reset : EditOp {
        override val bytes: Long = 0L
    }

    /** A new automatic alpha for the same photo, with the edits cleared ([RefineSession.replaceBase]). */
    class Base(val alpha: RunLengthAlpha) : EditOp {
        override val bytes: Long get() = alpha.bytes
    }
}

/** A 0/1 selection as runs: a [RunLengthAlpha] of 0 and 1 values. */
internal typealias BitRuns = RunLengthAlpha

/** A float array as runs of equal values (bit-pattern equality), 8 bytes per run. */
internal class RunLengthAlpha(source: FloatArray) {
    private val values: FloatArray
    private val lengths: IntArray

    init {
        var runs = 0
        for (i in source.indices) if (i == 0 || source[i].toRawBits() != source[i - 1].toRawBits()) runs++
        values = FloatArray(runs)
        lengths = IntArray(runs)
        var run = -1
        for (i in source.indices) {
            if (i == 0 || source[i].toRawBits() != source[i - 1].toRawBits()) {
                run++
                values[run] = source[i]
            }
            lengths[run]++
        }
    }

    val bytes: Long get() = values.size * 8L

    fun decode(size: Int): FloatArray {
        val out = FloatArray(size)
        var position = 0
        for (run in values.indices) {
            out.fill(values[run], position, position + lengths[run])
            position += lengths[run]
        }
        return out
    }
}

/** Photos kept off screen that an [EditBudget] may drop. */
internal interface DroppablePhotos {
    /** Drops the oldest photo kept off screen; false when there is none. */
    fun dropOldest(): Boolean
}

/**
 * Edit-history bytes of one editing session, shared by its photos: the two live arrays of each photo, and its ops and
 * checkpoints. Over [limit], the oldest photo kept off screen is dropped first, then the oldest undoable ops are folded.
 * The photo on screen is never dropped, so the limit is soft when that photo alone is over it. Histories register in
 * creation order.
 */
internal class EditBudget(private val limit: Long = EDIT_HISTORY_BUDGET_BYTES) {
    internal var used: Long = 0L
    private val histories = ArrayList<EditHistory>()
    private val kept = ArrayList<DroppablePhotos>()

    internal fun register(history: EditHistory) {
        histories += history
    }

    internal fun unregister(history: EditHistory) {
        histories.remove(history)
    }

    internal fun registerKept(photos: DroppablePhotos) {
        kept += photos
    }

    internal fun unregisterKept(photos: DroppablePhotos) {
        kept.remove(photos)
    }

    /** Drops kept photos, then folds ops, until the history fits the [limit], or nothing is left to drop or fold. */
    internal fun trim() {
        while (used > limit) {
            // Each drop or fold removes something, so the loop ends.
            if (kept.any { it.dropOldest() }) continue
            if (!histories.any { it.foldOldest() }) break
        }
    }
}

/**
 * The alpha history of one photo. [base] is its automatic alpha. [undo] and [redo] move the cursor through the ops; a push
 * after an undo drops the redo tail. A checkpoint every [CHECKPOINT_INTERVAL] ops keeps undo cheap. Over the [budget], the
 * oldest undoable ops are folded into a checkpoint, so undo stops there. The two live arrays count against the [budget] too.
 * Pure Kotlin on primitive arrays.
 */
internal class EditHistory(
    base: FloatArray,
    private val w: Int,
    private val h: Int,
    private val budget: EditBudget = EditBudget(),
) {
    /** The alpha and the automatic alpha after [applied] ops. */
    private class Checkpoint(val alpha: RunLengthAlpha, val automatic: RunLengthAlpha) {
        val bytes: Long get() = alpha.bytes + automatic.bytes
    }

    private class Alphas(val alpha: FloatArray, val automatic: FloatArray)

    private val size = w * h
    private val checkpoints = TreeMap<Int, Checkpoint>()
    /** `ops[i]` is the op number `first + i`; op numbers count from the oldest state that undo can still reach. */
    private val ops = ArrayList<EditOp>()
    private var first = 0
    private var cursor = 0
    private var alpha: FloatArray
    private var automatic: FloatArray
    /** Bytes this history holds in the budget: its two live arrays, its checkpoints and its ops. */
    private var held = 2L * size * Float.SIZE_BYTES

    init {
        require(w > 0 && h > 0) { "Photo size must be positive" }
        require(base.size == size) { "Alpha must be ${w}x$h" }
        alpha = base.copyOf()
        automatic = base.copyOf()
        budget.used += held
        budget.register(this)
        addCheckpoint(0)
        budget.trim()
    }

    val canUndo: Boolean get() = cursor > first

    val canRedo: Boolean get() = cursor < first + ops.size

    /** True when the alpha differs from the automatic one. */
    val isEdited: Boolean get() = !alpha.contentEquals(automatic)

    fun currentAlpha(): FloatArray = alpha.copyOf()

    fun automaticAlpha(): FloatArray = automatic.copyOf()

    fun push(op: EditOp) {
        val next = applyOp(op, Alphas(alpha, automatic))
        dropRedoTail()
        ops += op
        held += op.bytes
        budget.used += op.bytes
        alpha = next.alpha
        automatic = next.automatic
        cursor++
        if (cursor % CHECKPOINT_INTERVAL == 0) addCheckpoint(cursor)
        budget.trim()
    }

    /** Undoes the last op and returns it, or null when nothing is left to undo. */
    fun undo(): EditOp? {
        if (!canUndo) return null
        cursor--
        val op = ops[cursor - first]
        rebuildAt(cursor)
        return op
    }

    /** Redoes the next op and returns it, or null when there is none. */
    fun redo(): EditOp? {
        if (!canRedo) return null
        val op = ops[cursor - first]
        val next = applyOp(op, Alphas(alpha, automatic))
        alpha = next.alpha
        automatic = next.automatic
        cursor++
        if (cursor % CHECKPOINT_INTERVAL == 0 && cursor !in checkpoints) addCheckpoint(cursor)
        budget.trim()
        return op
    }

    /**
     * Folds the ops before the next checkpoint into that checkpoint. False when no op can be folded (undo would not reach
     * a state that is still undoable).
     */
    internal fun foldOldest(): Boolean {
        val next = checkpoints.higherKey(first) ?: return false
        if (next >= cursor) return false
        for (index in first until next) {
            held -= ops[index - first].bytes
            budget.used -= ops[index - first].bytes
        }
        ops.subList(0, next - first).clear()
        checkpoints.headMap(next).keys.toList().forEach { removeCheckpoint(it) }
        first = next
        return true
    }

    /** Releases the history: its bytes leave the budget, and it can no longer be used. */
    fun close() {
        budget.unregister(this)
        budget.used -= held
        held = 0L
        ops.clear()
        checkpoints.clear()
    }

    private fun applyOp(op: EditOp, state: Alphas): Alphas = when (op) {
        is EditOp.Hard -> Alphas(refineAlpha(op.mode, op.selected.decode(size), state.alpha, state.automatic), state.automatic)
        is EditOp.Brush -> {
            val mask = brushMask(op.pairs(), op.radiusPx, op.featherPx, w, h)
            Alphas(refineAlpha(op.mode, mask, state.alpha, state.automatic), state.automatic)
        }
        is EditOp.Soft -> Alphas(refineAlpha(op.mode, op.mask.decode(size), state.alpha, state.automatic), state.automatic)
        EditOp.Reset -> Alphas(state.automatic.copyOf(), state.automatic)
        is EditOp.Base -> op.alpha.decode(size).let { Alphas(it, it.copyOf()) }
    }

    /** Recomputes the state at [target] from the nearest checkpoint at or before it. */
    private fun rebuildAt(target: Int) {
        val start = checkNotNull(checkpoints.floorEntry(target))
        var state = Alphas(start.value.alpha.decode(size), start.value.automatic.decode(size))
        for (index in start.key until target) state = applyOp(ops[index - first], state)
        alpha = state.alpha
        automatic = state.automatic
    }

    private fun dropRedoTail() {
        while (ops.size > cursor - first) {
            val dropped = ops.removeAt(ops.size - 1)
            held -= dropped.bytes
            budget.used -= dropped.bytes
        }
        while (checkpoints.lastKey() > cursor) removeCheckpoint(checkpoints.lastKey())
    }

    private fun addCheckpoint(index: Int) {
        val checkpoint = Checkpoint(RunLengthAlpha(alpha), RunLengthAlpha(automatic))
        checkpoints[index] = checkpoint
        held += checkpoint.bytes
        budget.used += checkpoint.bytes
    }

    private fun removeCheckpoint(index: Int) {
        val checkpoint = checkpoints.remove(index) ?: return
        held -= checkpoint.bytes
        budget.used -= checkpoint.bytes
    }
}

/**
 * The photos of one editing session that are not on screen, in order: the photos before it, and the photos after it that
 * were undone. Each photo is written to a cache file in [directory] and keeps its own [RefineSession], so undo across a
 * "Cut out again" restores the photo and its alpha history where they were. Over the [budget], the oldest of these photos
 * is dropped, and undo stops at the oldest one kept. [release] frees a photo that was read back but could not be moved on
 * screen. [close] deletes the files.
 */
internal class PhotoHistory<P>(
    private val budget: EditBudget,
    private val directory: File,
    private val write: (P, File) -> Unit,
    private val read: (File) -> P,
    private val release: (P) -> Unit,
) : DroppablePhotos {
    private class Step(val file: File, val session: RefineSession, val fromRedo: Boolean)

    /** A photo brought back on screen by [back] or [forward]. */
    class Restored<T>(val photo: T, val session: RefineSession, val fromRedo: Boolean)

    /** Photos before the one on screen; the nearest is last. */
    private val before = ArrayDeque<Step>()

    /** Photos after the one on screen, undone by [back]; the nearest is last. */
    private val after = ArrayDeque<Step>()

    init {
        // Files left by an editor that did not close (its process died): no photo refers to them any more.
        directory.listFiles()?.forEach { it.delete() }
        budget.registerKept(this)
    }

    val canGoBack: Boolean get() = before.isNotEmpty()

    val canGoForward: Boolean get() = after.isNotEmpty()

    /** Cut out again: the photo on screen is kept, and the undone photos after it are dropped. */
    fun cutOut(current: P, session: RefineSession, fromRedo: Boolean) {
        before.addLast(spill(current, session, fromRedo))
        dropAfter()
    }

    /** Undo across a cut out: the photo on screen goes to [after]; null when there is no earlier photo. */
    fun back(current: P, session: RefineSession, fromRedo: Boolean): Restored<P>? {
        val step = before.lastOrNull() ?: return null
        val arriving = read(step.file)
        after.addLast(spillFor(arriving, current, session, fromRedo))
        before.removeLast()
        step.file.delete()
        return Restored(arriving, step.session, step.fromRedo)
    }

    /** Redo across a cut out: the photo on screen goes to [before]; null when there is no undone photo. */
    fun forward(current: P, session: RefineSession, fromRedo: Boolean): Restored<P>? {
        val step = after.lastOrNull() ?: return null
        val arriving = read(step.file)
        before.addLast(spillFor(arriving, current, session, fromRedo))
        after.removeLast()
        step.file.delete()
        return Restored(arriving, step.session, step.fromRedo)
    }

    /** Drops the oldest photo kept off screen: the first of [before], else the nearest of [after] (the oldest there). */
    override fun dropOldest(): Boolean {
        val step = before.removeFirstOrNull() ?: after.removeLastOrNull() ?: return false
        step.file.delete()
        step.session.close()
        return true
    }

    /** Deletes every photo file and releases the sessions that are not on screen. */
    fun close() {
        budget.unregisterKept(this)
        (before + after).forEach { step ->
            step.file.delete()
            step.session.close()
        }
        before.clear()
        after.clear()
    }

    /** Spills [current] for a move. When that fails, [arriving] is released: nothing on screen will show it. */
    private fun spillFor(arriving: P, current: P, session: RefineSession, fromRedo: Boolean): Step =
        try {
            spill(current, session, fromRedo)
        } catch (throwable: Throwable) {
            release(arriving)
            throw throwable
        }

    private fun spill(photo: P, session: RefineSession, fromRedo: Boolean): Step {
        directory.mkdirs()
        val file = File(directory, "${UUID.randomUUID()}.png")
        write(photo, file)
        return Step(file, session, fromRedo)
    }

    private fun dropAfter() {
        after.forEach { step ->
            step.file.delete()
            step.session.close()
        }
        after.clear()
    }
}
